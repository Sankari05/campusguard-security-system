# ── Routes: Video Feed ────────────────────────────────────────
@router.get("/video_feed")
def video_feed():
    """
    MJPEG live video streaming endpoint.
    Serves multipart/x-mixed-replace JPEG frames generated by the background session thread.
    Includes automated HUD reconnection frames when hardware is offline.
    """
    return StreamingResponse(
        _sess.generate_frames(),
        media_type="multipart/x-mixed-replace; boundary=frame",
        headers={
            "Cache-Control": "no-cache, no-store, must-revalidate",
            "Pragma": "no-cache",
            "Expires": "0",
        }
    )


# ── Routes: Live Attendance Session Controls ──────────────────
@router.post("/api/session/start")
@router.post("/session/start")
def session_start(req: StartSessionReq = StartSessionReq(), user: dict = Depends(teacher_required)):
    """Start face-recognition attendance session for a given period."""
    state = _sess._SESSION_STATE
    t = state.get("thread")
    if t and not t.is_alive():
        state["running"] = False
        state["thread"] = None

    if state.get("running"):
        raise HTTPException(status_code=409, detail="A session is already running. Please stop it first.")

    period = req.period.strip()
    if not period:
        raise HTTPException(status_code=400, detail="Period name is required.")

    result = _sess.start_session(period)
    if not result.get("ok"):
        raise HTTPException(status_code=500, detail=result.get("error", "Failed to start camera session."))

    db.log_audit(user.get("sub", "teacher"), "session_start", period)
    return {
        "status": "started",
        "period": period,
        "stream": "/video_feed",
        "message": f"Session active for {period}",
    }


@router.post("/api/session/stop")
@router.post("/session/stop")
def session_stop(user: dict = Depends(teacher_required)):
    """Stop the active face-recognition attendance session cleanly."""
    _sess.stop_session()
    db.log_audit(user.get("sub", "teacher"), "session_stop", _sess._SESSION_STATE.get("period", ""))
    return {"status": "stopped", "message": "Camera session terminated."}


