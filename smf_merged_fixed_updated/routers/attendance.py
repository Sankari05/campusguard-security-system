# ── Routes: Attendance Records & Override ─────────────────────
@router.get("/api/attendance/today")
def api_attendance_today(period: Optional[str] = None, _: dict = Depends(get_current_user)):
    """Return attendance rows marked today, optionally filtered by period."""
    rows = db.get_today_attendance(period)
    return [dict(r) for r in rows]


@router.get("/api/attendance/summary")
def api_attendance_summary(date: Optional[str] = None, _: dict = Depends(get_current_user)):
    """Return aggregated daily attendance summary (present/absent/percentage)."""
    d = date or datetime.now().strftime("%Y-%m-%d")
    return db.get_daily_summary(d)


@router.get("/api/attendance/date/{date_str}")
def api_attendance_by_date(date_str: str, period: Optional[str] = None, _: dict = Depends(get_current_user)):
    """Fetch attendance records for a specific date (YYYY-MM-DD)."""
    rows = db.get_attendance_by_date(date_str, period)
    return [dict(r) for r in rows]


@router.post("/api/attendance/override")
def api_attendance_override(req: OverrideReq, user: dict = Depends(teacher_required)):
    """Teacher/HOD/Admin override for student attendance record."""
    ok = db.override_attendance(
        student_id=req.student_id,
        date=req.date,
        period=req.period,
        status=req.status,
        reason=req.reason,
        marked_by=user.get("sub", "teacher"),
    )
    if not ok:
        raise HTTPException(status_code=500, detail="Failed to apply attendance override.")
    db.log_audit(user.get("sub", "teacher"), "attendance_override", req.student_id, f"{req.date}:{req.status}")
    return {"ok": True, "message": "Attendance record updated."}


@router.get("/api/export/csv")
def api_export_csv(period: Optional[str] = None, _: dict = Depends(get_current_user)):
    """Export today's attendance records as a downloadable CSV."""
    today_str = datetime.now().strftime("%Y-%m-%d")
    rows = db.get_today_attendance(period)
    out = io.StringIO()
    writer = csv.DictWriter(out, fieldnames=["name", "student_id", "period", "date", "time", "confidence", "engine"])
    writer.writeheader()
    for r in rows:
        writer.writerow({k: r.get(k, "") for k in writer.fieldnames})
    out.seek(0)
    return StreamingResponse(
        iter([out.read()]),
        media_type="text/csv",
        headers={"Content-Disposition": f"attachment; filename=attendance_{today_str}.csv"}
    )
